    browser = None
    context = None

    try:
        pw = await async_api.async_playwright().start()
        browser = await pw.chromium.launch(
            headless=True,
            args=[
                "--window-size=1280,720",
                "--disable-dev-shm-usage",
                "--ipc=host",
                "--single-process"
            ],
        )
        context = await browser.new_context()
        context.set_default_timeout(15000)
        page = await context.new_page()
        # -> navigate
        await page.goto("http://localhost:5173")
        try:
            await page.wait_for_load_state("domcontentloaded", timeout=5000)
        except Exception:
            pass
        
        # -> Wait briefly to allow the SPA to finish loading, then reload/navigate to http://localhost:5173/login and check for interactive elements (login form).
        await page.goto("http://localhost:5173/login")
        try:
            await page.wait_for_load_state("domcontentloaded", timeout=5000)
        except Exception:
            pass
        
        # -> Open a new tab and navigate to http://127.0.0.1:5173/login to check whether the login form renders there.
        await page.goto("http://127.0.0.1:5173/login")
        try:
            await page.wait_for_load_state("domcontentloaded", timeout=5000)
        except Exception:
            pass
        
        # --> Test blocked (AST guard fallback)
        raise AssertionError("Test blocked during agent run: " + "TEST BLOCKED The login page could not be reached \u2014 the frontend SPA did not load in the browser, preventing the login form from appearing. Observations: - Both http://localhost:5173/login and http://127.0.0.1:5173/login displayed a blank/unrendered page with 0 interactive elements. - Multiple reloads and waits (several attempts) did not cause the SPA to render, and the login form was never visi...")
        await asyncio.sleep(5)
    finally:
        if context:
            await context.close()
        if browser:
            await browser.close()
        if pw:
            await pw.stop()

